const isTranslationKey = (str) => /^[a-z0-9_]+(?:\.[a-z0-9_]+)+$/i.test(str);

const getValueByPath = (source, path) => {
  if (!source) return undefined;
  if (isTranslationKey(path)) {
    return path.split(".").reduce((current, segment) => current?.[segment], source);
  }
  return source[path];
};

const interpolate = (template, values = {}) => {
  if (typeof template !== "string") return template;
  return template.replace(/\{\{\s*([^}]+)\s*\}\}/g, (_, rawKey) => {
    const key = rawKey.trim();
    return values[key] ?? "";
  });
};

export const translateCatalog = (catalog, key, options = {}) => {
  const message = getValueByPath(catalog, key) || key;
  if (typeof message === "string") {
    return interpolate(message, options);
  }
  return options.fallback ?? key;
};

export const translateApp = (key, options = {}) => {
  return translateCatalog(en, key, options);
};

export const resolveLocalizedValue = (value, language = "en", fallback = "") => {
  if (typeof value === "string" || typeof value === "number") {
    return value;
  }
  if (value && typeof value === "object") {
    return value.en ?? Object.values(value)[0] ?? fallback;
  }
  return fallback;
};

